"""Re-check PERSISTENCE_DECAY: pick it on the first 6 backtest months, report it on the last 6.

Trains the 12-month backtest once with the blend switched off, then applies each candidate decay
to the raw predictions (the blend never changes training). Writes docs/decay_tuning.md; does not
change PERSISTENCE_DECAY or the headline backtest.

Run (local warehouse):  python analysis/tune_decay.py   (~1-3 min)
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

from gridcarbon import forecast as fc
from gridcarbon.config import Settings
from gridcarbon.load import connect

ROOT = Path(__file__).resolve().parents[1]
CANDIDATES = [1, 1.5, 2, 3, 4, 6, 8, 12, 24]
sys.stdout.reconfigure(encoding="utf-8")

con = connect(Settings(db_target="local"))
grid, wx = fc.load_history(con)
neso = fc.load_neso_forecasts(con)
# raw model output: blend returns the model prediction untouched
fc.blend = lambda rows, model_pred: np.asarray(model_pred)  # type: ignore[assignment]
preds = fc.backtest(grid, wx, fc.holidays(), months=12, neso=neso)
# Rows without a last known actual get no blend, as live (and as in analysis/backtest.py).
preds["last_actual"] = preds["last_actual"].fillna(preds["model"])


def mae(df: pd.DataFrame, decay: float | None, leads: tuple[int, int] = (1, 96)) -> float:
    df = df[df["lead"].between(*leads)]
    if decay is None:
        pred = df["model"]
    else:
        w = np.exp(-(df["lead"] - 1) / decay)
        pred = w * df["last_actual"] + (1 - w) * df["model"]
    return float((pred - df["y"]).abs().mean())


months = preds["period_from"].dt.tz_convert("UTC").dt.strftime("%Y-%m")
order = sorted(months.unique())
first, last = preds[months.isin(order[:6])], preds[months.isin(order[6:])]
best = min(CANDIDATES, key=lambda d: mae(first, d))
rows = [
    {
        "decay": d,
        "first 6 mo, all leads": mae(first, d),
        "last 6 mo, leads 1-4": mae(last, d, (1, 4)),
        "last 6 mo, all leads": mae(last, d),
    }
    for d in [None, *CANDIDATES]
]
table = pd.DataFrame(rows).round(2)
table["decay"] = table["decay"].map(lambda d: "no blend" if pd.isna(d) else f"{d:g}")
md = "\n".join(
    "| " + " | ".join(map(str, r)) + " |"
    for r in [table.columns, ["---"] * len(table.columns), *table.to_numpy()]
)
report = f"""# Persistence decay check

_Generated by `analysis/tune_decay.py`. Weight on the last known actual is exp(-(lead-1)/decay).
Decay is chosen on the first 6 backtest months; the last 6 are for checking. 1.5, 2 and 3 tie
on the first 6 (all leads is nearly flat), so 2 was kept using the later months' leads 1-4: a
check, not a clean holdout. MAE in
gCO₂/kWh. Live setting: `PERSISTENCE_DECAY = {fc.PERSISTENCE_DECAY}`. Best on the first 6 months:
**{best}**._

{md}
"""
(ROOT / "docs" / "decay_tuning.md").write_text(report, encoding="utf-8")
print(report)
